// ── API pública ────────────────────────────────────────────────
export const MARCAS = Object.keys(MARCAS_MODELOS);

export function getModelos(marca) {
  return MARCAS_MODELOS[marca] || [];
}

export function sugerirMarcas(texto) {
  if (!texto || texto.trim() === '') return MARCAS;
  const q = texto.toLowerCase();
  return MARCAS.filter(m => m.toLowerCase().includes(q));
}

export function sugerirModelos(marca, texto) {
  // Si no hay marca, buscar en todas
  const modelos = marca && marca !== 'Otras marcas'
    ? getModelos(marca)
    : Object.values(MARCAS_MODELOS).flat();
  if (!texto || texto.trim() === '') return modelos.slice(0, 12);
  const q = texto.toLowerCase();
  return modelos.filter(m => m.toLowerCase().includes(q)).slice(0, 12);
}

export function sugerirComponentes(texto) {
  if (!texto || texto.trim() === '') return COMPONENTES.slice(0, 8);
  const q = texto.toLowerCase();
  return COMPONENTES.filter(c => c.toLowerCase().includes(q)).slice(0, 10);
}

export function claveAgrupacion(marca, modelo, repuesto) {
  const norm = s => (s || '').toLowerCase().trim()
    .replace(/\s+/g, ' ')
    .replace(/[áàä]/g, 'a').replace(/[éèë]/g, 'e')
    .replace(/[íìï]/g, 'i').replace(/[óòö]/g, 'o').replace(/[úùü]/g, 'u');
  return `${norm(marca)}|${norm(modelo)}|${norm(repuesto)}`;
}

// ── Guardar marca/modelo nuevo en localStorage para sugerencias futuras ──
export function guardarMarcaPersonalizada(marca, modelo) {
  try {
    const key      = 'rp_marcas_custom';
    const existing = JSON.parse(localStorage.getItem(key) || '{}');
    if (!existing[marca]) existing[marca] = [];
    if (modelo && !existing[marca].includes(modelo)) {
      existing[marca] = [modelo, ...existing[marca]].slice(0, 50);
    }
    localStorage.setItem(key, JSON.stringify(existing));
  } catch {}
}

export function getMarcasPersonalizadas() {
  try {
    return JSON.parse(localStorage.getItem('rp_marcas_custom') || '{}');
  } catch { return {}; }
}

// Sugerencias combinando catálogo + personalizadas
export function sugerirMarcasCompleto(texto) {
  const personalizadas = Object.keys(getMarcasPersonalizadas());
  const todas = [...new Set([...MARCAS, ...personalizadas])];
  if (!texto || texto.trim() === '') return todas;
  const q = texto.toLowerCase();
  return todas.filter(m => m.toLowerCase().includes(q));
}

export function sugerirModelosCompleto(marca, texto) {
  const personalizadas = getMarcasPersonalizadas();
  const modelosCatalogo    = marca ? getModelos(marca) : Object.values(MARCAS_MODELOS).flat();
  const modelosPersonalizados = marca ? (personalizadas[marca] || []) : Object.values(personalizadas).flat();
  const todos = [...new Set([...modelosPersonalizados, ...modelosCatalogo])];
  if (!texto || texto.trim() === '') return todos.slice(0, 12);
  const q = texto.toLowerCase();
  return todos.filter(m => m.toLowerCase().includes(q)).slice(0, 12);
}
